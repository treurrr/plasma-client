#!/usr/bin/env python3
"""Writes data/block_sounds.txt: which sound type every block has, and that
type's five sound events with its volume and pitch.

The reports do not say, so tools/BlockSoundsExport.java asks the game itself:
it is compiled against the player's own remapped client jar (the same class
path tools/oracle/run.py uses), reads each block's default state's sound type,
and prints one row per block. The table is written whole or not at all.

Usage: gen_block_sounds.py [out.txt]
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "oracle"))
import run  # noqa: E402


def main(args):
    out = Path(args[0]) if args else HERE.parent / "data" / "block_sounds.txt"
    cp = run.classpath()
    with tempfile.TemporaryDirectory() as build:
        subprocess.run(["javac", "-cp", cp, "-d", build, str(HERE / "BlockSoundsExport.java")], check=True)
        printed = subprocess.run(["java", "-cp", build + os.pathsep + cp, "BlockSoundsExport"],
                                 capture_output=True, text=True, check=True, cwd=build).stdout
    rows = []
    for line in printed.splitlines():
        at = line.find("ROW\t")
        if at < 0:
            continue
        block, kind, volume, pitch, *events = line[at + 4:].split("\t")
        volume = format(float(volume), "g")
        pitch = format(float(pitch), "g")
        rows.append("\t".join([block, kind, volume, pitch, *events]))
    if len(rows) < 1000 or any(row.count("\t") != 8 for row in rows):
        sys.exit(f"the game printed {len(rows)} rows; nothing written")
    rows.sort()
    text = ("# block\ttype\tvolume\tpitch\tbreak\tstep\tplace\thit\tfall\n"
            "# generated by tools/gen_block_sounds.py from the game's own sound types; sorted by registry name\n"
            + "\n".join(rows) + "\n")
    tmp = out.with_suffix(".tmp")
    tmp.write_text(text)
    tmp.replace(out)
    print(f"{len(rows)} blocks written to {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
