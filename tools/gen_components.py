#!/usr/bin/env python3
"""Generate the data component table from Mojang's registries.json reports.

Usage: gen_components.py <protocol>=<reports/registries.json> ...

Writes src/proto/components_gen.cpp: every protocol's data component types in
its own numbering, and the wire layout of each, taken from
tools/component_layouts.txt, and the entries of every registry a layout
switches on. A type without a layout, a layout for a type no report has, or a
case that names no registry entry stops the run: the table is complete or it
is not written.
"""
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src/proto/components_gen.cpp"
LAYOUTS = ROOT / "tools/component_layouts.txt"


def load(args):
    versions = []
    for arg in args:
        protocol, _, path = arg.partition("=")
        if not protocol.isdigit() or not path:
            sys.exit(__doc__)
        versions.append((int(protocol), json.loads(Path(path).read_text())))
    versions.sort()
    if len({p for p, _ in versions}) != len(versions):
        sys.exit("a protocol is given twice")
    return versions


def registry(report, protocol, name):
    if name not in report:
        sys.exit(f"protocol {protocol} has no registry {name}")
    entries = report[name]["entries"]
    names = sorted(entries, key=lambda entry: entries[entry]["protocol_id"])
    if [entries[n]["protocol_id"] for n in names] != list(range(len(names))):
        sys.exit(f"protocol {protocol}: {name} ids are not 0..n-1")
    return names


def switches(layout):
    """(registry, case names) for every switch(...){...} in a layout."""
    found = []
    for match in re.finditer(r"switch\(([^)]*)\)\{", layout):
        depth, start, i = 1, match.end(), match.end()
        while depth:
            if layout[i] == "{":
                depth += 1
            elif layout[i] == "}":
                depth -= 1
            i += 1
        depth, top = 0, ""
        for char in layout[start:i - 1]:
            depth += char in "({"
            top += char if depth == 0 else " "
            depth -= char in ")}"
        cases = re.findall(r"([a-z_]+):", top)
        found.append((match.group(1).strip(), cases))
    return found


def read_layouts():
    """Named types first (`type <name> = <layout>`), then `<component> <layout>`."""
    types = {}
    components = {}
    for number, raw in enumerate(LAYOUTS.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("type "):
            match = re.fullmatch(r"type\s+([a-z_][a-z0-9_]*)\s*=\s*(.+)", line)
            if not match:
                sys.exit(f"{LAYOUTS.name}:{number}: bad type line")
            types[match.group(1)] = match.group(2).strip()
            continue
        name, _, layout = line.partition(" ")
        if not name.startswith("minecraft:") or not layout.strip():
            sys.exit(f"{LAYOUTS.name}:{number}: bad component line")
        if name in components:
            sys.exit(f"{LAYOUTS.name}:{number}: {name} given twice")
        components[name] = layout.strip()
    return types, components


def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(versions, types, layouts):
    ids = [(protocol, registry(report, protocol, "minecraft:data_component_type"))
           for protocol, report in versions]
    every = sorted({name for _, names in ids for name in names})
    missing = [name for name in every if name not in layouts]
    if missing:
        sys.exit("no layout for: " + ", ".join(missing))
    extra = sorted(set(layouts) - set(every))
    if extra:
        sys.exit("layout for a component no report has: " + ", ".join(extra))

    out = ["// Generated by tools/gen_components.py. Do not edit by hand.",
           '#include "components_gen.hpp"',
           "",
           "namespace mcpp::proto::generated {",
           "",
           "const std::vector<NamedLayout>& component_types() {",
           "    static const std::vector<NamedLayout> types = {"]
    for name, layout in sorted(types.items()):
        out.append(f"        {{{quote(name)}, {quote(layout)}}},")
    out += ["    };", "    return types;", "}", ""]
    out += ["const std::vector<NamedLayout>& component_layouts() {",
            "    static const std::vector<NamedLayout> layouts = {"]
    for name in every:
        out.append(f"        {{{quote(name)}, {quote(layouts[name])}}},")
    out += ["    };", "    return layouts;", "}", ""]
    # Command parsers are read by hand, but by name, in commands.cpp.
    switched = {"minecraft:command_argument_type": set()}
    for layout in list(types.values()) + list(layouts.values()):
        for name, cases in switches(layout):
            switched.setdefault(name, set()).update(cases)
    tables = {"minecraft:data_component_type": dict(ids)}
    for name, cases in sorted(switched.items()):
        tables[name] = {}
        for protocol, report in versions:
            names = registry(report, protocol, name)
            unknown = sorted(c for c in cases if "minecraft:" + c not in names)
            if unknown:
                sys.exit(f"protocol {protocol}: {name} has no " + ", ".join(unknown))
            tables[name][protocol] = names

    out += ["const std::vector<std::string_view>* registry_entries(std::string_view registry,",
            "                                                    int32_t protocol) {"]
    for name, per_protocol in tables.items():
        for protocol, names in per_protocol.items():
            out.append(f"    if (registry == {quote(name)} && protocol == {protocol}) {{")
            out.append("        static const std::vector<std::string_view> names = {")
            line = "           "
            for entry in names:
                piece = " " + quote(entry) + ","
                if len(line) + len(piece) > 99:
                    out.append(line)
                    line = "           "
                line += piece
            out.append(line)
            out += ["        };", "        return &names;", "    }"]
    out += ["    return nullptr;", "}", "", "} // namespace mcpp::proto::generated", ""]
    return "\n".join(out)


def write(path, text):
    handle, temp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".")
    with os.fdopen(handle, "w") as stream:
        stream.write(text)
    os.replace(temp, path)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    versions = load(sys.argv[1:])
    types, layouts = read_layouts()
    write(SOURCE, emit(versions, types, layouts))
    print(f"{SOURCE.relative_to(ROOT)}: {len(layouts)} components, {len(types)} named types, "
          f"protocols {', '.join(str(p) for p, _ in versions)}")


if __name__ == "__main__":
    main()
